// Packs the panel art in art/ into src/page/art.js as data URIs. The panel runs inside the Web App's
// page, where an extension file URL isn't available, and the page allows data: images.
// Usage: node scripts/build-art.mjs   (see art/README.md for the file names)
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const TYPES = { '.png': 'image/png', '.svg': 'image/svg+xml', '.webp': 'image/webp' };

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? files(full) : TYPES[extname(name)] ? [full] : [];
  });
}

const art = {};
for (const file of files(join(root, 'art')).sort()) {
  const key = file.slice(join(root, 'art').length + 1).replace(/\\/g, '/').replace(/\.[^.]+$/, '');
  art[key] = `data:${TYPES[extname(file)]};base64,${readFileSync(file).toString('base64')}`;
}

const out = `// Generated by scripts/build-art.mjs from art/. Don't edit by hand.
(function (root) {
  'use strict';

  (root.FutFox = root.FutFox || {}).art = ${JSON.stringify(art, null, 2).replace(/\n/g, '\n  ')};
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
writeFileSync(join(root, 'src/page/art.js'), out);
console.log(`src/page/art.js: ${Object.keys(art).join(', ') || 'no art'}`);
